#!/usr/bin/env bash
# dot-ai-init.sh creates the dot-ai/ tree in a target repo. Idempotent.
# Usage: dot-ai-init.sh [target-dir]
set -euo pipefail

target="${1:-.}"
script_dir="$(cd "$(dirname "$0")" && pwd)"
assets="$(cd "$script_dir/../assets" && pwd)"

mkdir -p "$target/dot-ai/research" "$target/dot-ai/refs" \
  "$target/dot-ai/handoffs/archive" "$target/dot-ai/assessments" \
  "$target/dot-ai/decisions" "$target/dot-ai/tracks" "$target/dot-ai/specs"

if [ ! -e "$target/specs" ]; then
  ln -s "dot-ai/specs" "$target/specs"
fi

if [ -d "$target/.specify" ] && [ ! -e "$target/.specify/assessments" ]; then
  ln -s "../dot-ai/assessments" "$target/.specify/assessments"
fi

if [ ! -f "$target/dot-ai/INDEX.md" ]; then
  printf '# INDEX\n\nGenerated by dot-ai-index. Do not edit by hand.\n' > "$target/dot-ai/INDEX.md"
fi

snippet="$assets/AGENTS-snippet.md"
if [ ! -f "$target/AGENTS.md" ]; then
  cp "$snippet" "$target/AGENTS.md"
elif ! grep -q "BEGIN MANAGED BLOCK: dot-ai" "$target/AGENTS.md"; then
  printf '\n' >> "$target/AGENTS.md"
  cat "$snippet" >> "$target/AGENTS.md"
fi

echo "dot-ai ready in $target"
