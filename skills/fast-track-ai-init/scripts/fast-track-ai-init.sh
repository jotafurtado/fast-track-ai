#!/usr/bin/env bash
# fast-track-ai-init.sh creates the fast-track-ai/ tree in a target repo. Idempotent.
# Usage: fast-track-ai-init.sh [target-dir]
set -euo pipefail

target="${1:-.}"
script_dir="$(cd "$(dirname "$0")" && pwd)"
assets="$(cd "$script_dir/../assets" && pwd)"

mkdir -p "$target/fast-track-ai/research" "$target/fast-track-ai/refs" \
  "$target/fast-track-ai/handoffs/archive" "$target/fast-track-ai/assessments" \
  "$target/fast-track-ai/decisions" "$target/fast-track-ai/tracks"

if [ ! -f "$target/fast-track-ai/INDEX.md" ]; then
  printf '# INDEX\n\nGenerated by fast-track-ai-index. Do not edit by hand.\n' > "$target/fast-track-ai/INDEX.md"
fi

snippet="$assets/AGENTS-snippet.md"
if [ ! -f "$target/AGENTS.md" ]; then
  cp "$snippet" "$target/AGENTS.md"
elif ! grep -q "BEGIN MANAGED BLOCK: fast-track-ai" "$target/AGENTS.md"; then
  printf '\n' >> "$target/AGENTS.md"
  cat "$snippet" >> "$target/AGENTS.md"
fi

echo "fast-track-ai ready in $target"
