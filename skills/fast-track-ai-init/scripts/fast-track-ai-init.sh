#!/usr/bin/env bash
# fast-track-ai-init.sh creates the fast-track-ai/ tree in a target repo. Idempotent.
# Usage: fast-track-ai-init.sh [target-dir]
set -euo pipefail

target="${1:-.}"
script_dir="$(cd "$(dirname "$0")" && pwd)"
assets="$(cd "$script_dir/../assets" && pwd)"
snippet="$assets/AGENTS-snippet.md"
agents="$target/AGENTS.md"
begin_count=0
end_count=0
begin_line=0
end_line=0

if [ -f "$agents" ]; then
  marker_info="$(awk '
    /^<!-- BEGIN MANAGED BLOCK: fast-track-ai/ { begin_count++; begin_line=NR }
    /^<!-- END MANAGED BLOCK: fast-track-ai -->/ { end_count++; end_line=NR }
    END { printf "%d %d %d %d\n", begin_count, end_count, begin_line, end_line }
  ' "$agents")"
  read -r begin_count end_count begin_line end_line <<< "$marker_info"
fi

if ! { [ "$begin_count" -eq 0 ] && [ "$end_count" -eq 0 ]; } &&
  ! { [ "$begin_count" -eq 1 ] && [ "$end_count" -eq 1 ] && [ "$begin_line" -lt "$end_line" ]; }; then
  echo "FAIL: malformed managed markers: BEGIN count $begin_count, END count $end_count (expected 0/0 or 1/1 in order)" >&2
  exit 1
fi

tmp="$(mktemp "${TMPDIR:-/tmp}/fast-track-ai-init.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
if [ ! -f "$agents" ]; then
  cat "$snippet" > "$tmp"
elif [ "$begin_count" -eq 0 ]; then
  cat "$agents" > "$tmp"
  printf '\n' >> "$tmp"
  cat "$snippet" >> "$tmp"
else
  if [ "$begin_line" -gt 1 ]; then
    head -n "$((begin_line - 1))" "$agents" > "$tmp"
  fi
  cat "$snippet" >> "$tmp"
  line_count="$(awk 'END { print NR }' "$agents")"
  if [ "$end_line" -lt "$line_count" ]; then
    tail -n "+$((end_line + 1))" "$agents" >> "$tmp"
  fi
fi

mkdir -p "$target/fast-track-ai/research" "$target/fast-track-ai/refs" \
  "$target/fast-track-ai/handoffs/archive" "$target/fast-track-ai/assessments" \
  "$target/fast-track-ai/decisions" "$target/fast-track-ai/tracks"

if [ ! -f "$target/fast-track-ai/INDEX.md" ]; then
  printf '# INDEX\n\nGenerated by fast-track-ai-index. Do not edit by hand.\n' > "$target/fast-track-ai/INDEX.md"
fi

if ! [ -f "$agents" ] || ! cmp -s "$tmp" "$agents"; then
  cat "$tmp" > "$agents"
fi

echo "fast-track-ai ready in $target"
